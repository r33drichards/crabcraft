struct Gen<'a> {
    m: &'a Module,
    project: String,
    /// WIT type name → definition, across every interface (one Go package).
    types: HashMap<&'a str, &'a Ty>,
    /// whether the generic Result[T, E] declaration is needed
    need_result: bool,
}

impl<'a> Gen<'a> {
    fn new(m: &'a Module, project: &str) -> Result<Self> {
        let mut g = Gen {
            m,
            project: project.to_string(),
            types: HashMap::new(),
            need_result: false,
        };
        for iface in m.exports.iter().chain(&m.imports) {
            for t in &iface.types {
                if g.types.insert(t.wit_name.as_str(), &t.ty).is_some() {
                    bail!(
                        "type `{}` is declared in more than one interface; the Go lane puts \
                         every type in one package — rename one of them",
                        t.wit_name
                    );
                }
            }
        }
        g.validate()?;
        g.need_result = g.scan_need_result()?;
        Ok(g)
    }

    /// Claim every top-level Go identifier this module will emit; duplicate
    /// or reserved names fail loudly here, before anything is written.
    fn validate(&self) -> Result<()> {
        let mut taken: HashMap<String, String> = RESERVED
            .iter()
            .map(|s| (s.to_string(), "the gen runtime/bindings".to_string()))
            .collect();
        let mut claim = |ident: String, what: String| -> Result<()> {
            if let Some(owner) = taken.get(&ident) {
                bail!("{what} maps to Go identifier `{ident}`, which collides with {owner}; rename it in the WIT");
            }
            taken.insert(ident, what);
            Ok(())
        };

        for iface in self.m.exports.iter().chain(&self.m.imports) {
            for t in &iface.types {
                let p = go_pascal(&t.wit_name);
                let what = format!("WIT type `{}` ({})", t.wit_name, iface.instance);
                claim(p.clone(), what.clone())?;
                claim(format!("encode{p}"), what.clone())?;
                claim(format!("decode{p}"), what.clone())?;
                match &t.ty {
                    // struct fields are their own (per-type) identifier scope
                    Ty::Record(fields) => {
                        let mut seen: HashMap<String, &str> = HashMap::new();
                        for (fname, _) in fields {
                            let fp = go_pascal(fname);
                            if let Some(prev) = seen.insert(fp.clone(), fname) {
                                bail!(
                                    "{what}: fields `{prev}` and `{fname}` both map to Go field `{fp}`; rename one in the WIT"
                                );
                            }
                        }
                    }
                    Ty::Enum(cases) => {
                        for c in cases {
                            claim(format!("{p}{}", go_pascal(c)), format!("{what} case `{c}`"))?;
                        }
                    }
                    Ty::Flags(flags) => {
                        if flags.len() > 64 {
                            bail!(
                                "flags `{}` has {} flags; the Go lane (type {p} uint64) supports at most 64",
                                t.wit_name,
                                flags.len()
                            );
                        }
                        for f in flags {
                            claim(format!("{p}{}", go_pascal(f)), format!("{what} flag `{f}`"))?;
                        }
                    }
                    Ty::Variant(cases) => {
                        // payload cases become struct fields next to the
                        // generated Tag discriminant: that struct is its own
                        // identifier scope, with Tag pre-reserved
                        let mut fields: HashMap<String, String> = HashMap::new();
                        fields.insert(
                            "Tag".to_string(),
                            "the generated Tag discriminant".to_string(),
                        );
                        for (c, payload) in cases {
                            let cp = go_pascal(c);
                            claim(format!("{p}Tag{cp}"), format!("{what} case `{c}`"))?;
                            claim(format!("New{p}{cp}"), format!("{what} case `{c}`"))?;
                            if payload.is_some() {
                                if let Some(prev) =
                                    fields.insert(cp.clone(), format!("payload case `{c}`"))
                                {
                                    bail!(
                                        "{what}: payload case `{c}` maps to Go field `{cp}`, which collides with {prev}; rename it in the WIT"
                                    );
                                }
                            }
                        }
                    }
                    _ => {}
                }
            }
        }
        for iface in &self.m.exports {
            let mut methods: HashMap<String, String> = HashMap::new();
            for f in &iface.funcs {
                let p = go_pascal(&f.wit_name);
                let what = format!("WIT function `{}` ({})", f.wit_name, iface.instance);
                claim(format!("handle{p}"), what.clone())?;
                claim(format!("decode{p}Args"), what.clone())?;
                if let Some(prev) = methods.insert(p.clone(), f.wit_name.clone()) {
                    bail!(
                        "WIT functions `{prev}` and `{}` both map to Go method `{p}`; rename one",
                        f.wit_name
                    );
                }
                self.validate_params(f, &what)?;
            }
        }
        for iface in &self.m.imports {
            let ip = go_pascal(iface_short(&iface.instance));
            for f in &iface.funcs {
                let what = format!("WIT import `{}` ({})", f.wit_name, iface.instance);
                claim(format!("{ip}{}", go_pascal(&f.wit_name)), what.clone())?;
                self.validate_params(f, &what)?;
            }
        }
        Ok(())
    }

    fn validate_params(&self, f: &Func, what: &str) -> Result<()> {
        let mut seen: HashMap<String, &str> = HashMap::new();
        for (name, _) in &f.params {
            if let Some(prev) = seen.insert(go_param(name), name) {
                bail!("{what}: params `{prev}` and `{name}` both map to the same Go name");
            }
        }
        Ok(())
    }

    /// Follow Named references to the defining type (alias chains too).
    fn resolve(&self, ty: &'a Ty) -> Result<&'a Ty> {
        let mut t = ty;
        for _ in 0..64 {
            match t {
                Ty::Named(n) => {
                    t = self
                        .types
                        .get(n.as_str())
                        .copied()
                        .ok_or_else(|| anyhow!("unresolved type reference `{n}`"))?;
                }
                _ => return Ok(t),
            }
        }
        bail!("type alias cycle while resolving `{ty:?}`");
    }

    fn classify(&self, f: &'a Func) -> Result<Ret<'a>> {
        let Some(rty) = &f.result else {
            return Ok(Ret::None);
        };
        if let Ty::Result(ok, errt) = self.resolve(rty)? {
            let ok = ok.as_deref();
            match errt.as_deref() {
                None => return Ok(Ret::ResStr { ok, has_msg: false }),
                Some(e) if matches!(self.resolve(e)?, Ty::String) => {
                    return Ok(Ret::ResStr { ok, has_msg: true });
                }
                Some(_) => return Ok(Ret::ResTyped(rty)),
            }
        }
        Ok(Ret::Plain(rty))
    }

    /// True if any value position needs the generic Result[T, E] type (a
    /// result NOT mapped to (T, error) at a function boundary).
    fn scan_need_result(&self) -> Result<bool> {
        fn walk(ty: &Ty) -> bool {
            match ty {
                Ty::Result(..) => true,
                Ty::List(t) | Ty::Option(t) => walk(t),
                Ty::Tuple(ts) => ts.iter().any(walk),
                Ty::Record(fs) => fs.iter().any(|(_, t)| walk(t)),
                Ty::Variant(cs) => cs.iter().any(|(_, t)| t.as_ref().is_some_and(walk)),
                _ => false,
            }
        }
        for iface in self.m.exports.iter().chain(&self.m.imports) {
            for t in &iface.types {
                if walk(&t.ty) {
                    return Ok(true);
                }
            }
            for f in &iface.funcs {
                if f.params.iter().any(|(_, t)| walk(t)) {
                    return Ok(true);
                }
                let needed = match self.classify(f)? {
                    Ret::None => false,
                    Ret::Plain(t) => walk(t),
                    Ret::ResStr { ok, .. } => ok.is_some_and(walk),
                    Ret::ResTyped(_) => true,
                };
                if needed {
                    return Ok(true);
                }
            }
        }
        Ok(false)
    }

    /// Go zero-value expression for a type (used by the scaffolded stubs).
    fn zero(&self, ty: &Ty, qual: &str, ind: usize) -> Result<String> {
        Ok(match ty {
            Ty::Bool => "false".to_string(),
            Ty::String => "\"\"".to_string(),
            Ty::List(_) | Ty::Option(_) => "nil".to_string(),
            Ty::Tuple(_) | Ty::Result(..) => format!("{}{{}}", go_ty(ty, qual, ind)?),
            Ty::Named(n) => match self.resolve(ty)? {
                Ty::Record(_) | Ty::Variant(_) => format!("{qual}{}{{}}", go_pascal(n)),
                Ty::Enum(_) | Ty::Flags(_) => "0".to_string(),
                under => self.zero(under, qual, ind)?,
            },
            _ => "0".to_string(), // ints, floats, char
        })
    }

    // -- named type declarations + codec helpers ------------------------------

    fn emit_named_ty(&self, w: &mut W, iface: &Iface, t: &NamedTy) -> Result<()> {
        let p = go_pascal(&t.wit_name);
        match &t.ty {
            Ty::Record(fields) => {
                w.line(format!(
                    "// {p} mirrors the WIT record `{}` ({}).",
                    t.wit_name, iface.instance
                ));
                let fs = fields
                    .iter()
                    .map(|(n, ft)| Ok((go_pascal(n), go_ty(ft, "", 1)?)))
                    .collect::<Result<Vec<_>>>()?;
                w.line(format!("type {p} struct {{"));
                w.buf.push_str(&align_fields(&fs, 1));
                w.line("}");
                w.line("");
                self.emit_record_codecs(w, &p, fields)?;
            }
            Ty::Variant(cases) => self.emit_variant(w, iface, t, cases)?,
            Ty::Enum(cases) => self.emit_enum(w, iface, t, cases),
            Ty::Flags(flags) => self.emit_flags(w, iface, t, flags),
            other => {
                // alias: identical Go type, helpers delegate to the structure
                w.line(format!(
                    "// {p} aliases the WIT type `{}` ({}).",
                    t.wit_name, iface.instance
                ));
                w.line(format!("type {p} = {}", go_ty(other, "", 0)?));
                w.line("");
                let body = self.encode_helper_body(other, "v")?;
                self.write_encode_helper(w, &p, body);
                let mut cx = Cx::new("return");
                let mut bw = W::new();
                bw.ind = 1;
                emit_decode(&mut bw, &mut cx, other, "v")?;
                self.write_decode_helper(w, &p, &bw.buf);
            }
        }
        Ok(())
    }

    fn emit_record_codecs(&self, w: &mut W, p: &str, fields: &[(String, Ty)]) -> Result<()> {
        let mut cx = Cx::new("return nil, err");
        let mut bw = W::new();
        bw.ind = 1;
        for (n, ft) in fields {
            emit_encode(&mut bw, &mut cx, ft, &format!("v.{}", go_pascal(n)))?;
        }
        let mut body = bw.buf;
        if cx.used_err {
            body = format!("\tvar err error\n{body}");
        }
        self.write_encode_helper(w, p, body);

        let mut cx = Cx::new("return");
        let mut bw = W::new();
        bw.ind = 1;
        for (n, ft) in fields {
            emit_decode(&mut bw, &mut cx, ft, &format!("v.{}", go_pascal(n)))?;
        }
        self.write_decode_helper(w, p, &bw.buf);
        Ok(())
    }

    fn write_encode_helper(&self, w: &mut W, p: &str, body: String) {
        w.line(format!(
            "func encode{p}(out []byte, v {p}) ([]byte, error) {{"
        ));
        w.buf.push_str(&body);
        w.line("\treturn out, nil");
        w.line("}");
        w.line("");
    }

    fn write_decode_helper(&self, w: &mut W, p: &str, body: &str) {
        w.line(format!("func decode{p}(d *Decoder) (v {p}, err error) {{"));
        w.buf.push_str(body);
        w.line("\treturn");
        w.line("}");
        w.line("");
    }

    /// Encode-helper body for an alias underlying type (expr is `v`).
    fn encode_helper_body(&self, ty: &Ty, expr: &str) -> Result<String> {
        let mut cx = Cx::new("return nil, err");
        let mut bw = W::new();
        bw.ind = 1;
        emit_encode(&mut bw, &mut cx, ty, expr)?;
        let mut body = bw.buf;
        if cx.used_err {
            body = format!("\tvar err error\n{body}");
        }
        Ok(body)
    }

    fn emit_enum(&self, w: &mut W, iface: &Iface, t: &NamedTy, cases: &[String]) {
        let p = go_pascal(&t.wit_name);
        w.line(format!(
            "// {p} mirrors the WIT enum `{}` ({}); consts in declaration order.",
            t.wit_name, iface.instance
        ));
        w.line(format!("type {p} int"));
        w.line("");
        w.line("const (");
        for (i, c) in cases.iter().enumerate() {
            if i == 0 {
                w.line(format!("\t{p}{} {p} = iota", go_pascal(c)));
            } else {
                w.line(format!("\t{p}{}", go_pascal(c)));
            }
        }
        w.line(")");
        w.line("");
        let n = cases.len();
        w.open(format!(
            "func encode{p}(out []byte, v {p}) ([]byte, error) {{"
        ));
        w.open(format!("if v < 0 || v >= {n} {{"));
        w.line(format!(
            "return nil, fmt.Errorf(\"invalid {p}: %d\", int(v))"
        ));
        w.close("}");
        w.line("return EncodeCase(out, uint32(v)), nil");
        w.close("}");
        w.line("");
        w.open(format!("func decode{p}(d *Decoder) ({p}, error) {{"));
        w.line(format!("c, err := d.EnumCase({n})"));
        w.line(format!("return {p}(c), err"));
        w.close("}");
        w.line("");
    }

    fn emit_flags(&self, w: &mut W, iface: &Iface, t: &NamedTy, flags: &[String]) {
        let p = go_pascal(&t.wit_name);
        w.line(format!(
            "// {p} mirrors the WIT flags `{}` ({}); bit i = flag i.",
            t.wit_name, iface.instance
        ));
        w.line(format!("type {p} uint64"));
        w.line("");
        w.line("const (");
        for (i, f) in flags.iter().enumerate() {
            if i == 0 {
                w.line(format!("\t{p}{} {p} = 1 << iota", go_pascal(f)));
            } else {
                w.line(format!("\t{p}{}", go_pascal(f)));
            }
        }
        w.line(")");
        w.line("");
        let n = flags.len();
        w.open(format!(
            "func encode{p}(out []byte, v {p}) ([]byte, error) {{"
        ));
        w.open(format!("if v>>{n} != 0 {{"));
        w.line(format!(
            "return nil, fmt.Errorf(\"invalid {p}: unknown bits in %#x\", uint64(v))"
        ));
        w.close("}");
        w.line(format!("bits := make([]bool, {n})"));
        w.open("for i := range bits {");
        w.line("bits[i] = v&(1<<i) != 0");
        w.close("}");
        w.line("return EncodeFlags(out, bits), nil");
        w.close("}");
        w.line("");
        w.open(format!("func decode{p}(d *Decoder) ({p}, error) {{"));
        w.line(format!("bits, err := d.Flags({n})"));
        w.open("if err != nil {");
        w.line("return 0, err");
        w.close("}");
        w.line(format!("var v {p}"));
        w.open("for i, set := range bits {");
        w.open("if set {");
        w.line("v |= 1 << i");
        w.close("}");
        w.close("}");
        w.line("return v, nil");
        w.close("}");
        w.line("");
    }

    fn emit_variant(
        &self,
        w: &mut W,
        iface: &Iface,
        t: &NamedTy,
        cases: &[(String, Option<Ty>)],
    ) -> Result<()> {
        let p = go_pascal(&t.wit_name);
        w.line(format!(
            "// {p} mirrors the WIT variant `{}` ({}): Tag selects the case",
            t.wit_name, iface.instance
        ));
        w.line(format!(
            "// ({p}Tag* consts, declaration order); for a payload case exactly the"
        ));
        w.line(format!(
            "// matching pointer field must be non-nil. Prefer the New{p}* constructors."
        ));
        let mut fields = vec![("Tag".to_string(), "int".to_string())];
        for (c, payload) in cases {
            if let Some(pt) = payload {
                fields.push((go_pascal(c), format!("*{}", go_ty(pt, "", 1)?)));
            }
        }
        w.line(format!("type {p} struct {{"));
        w.buf.push_str(&align_fields(&fields, 1));
        w.line("}");
        w.line("");
        w.line("const (");
        for (i, (c, _)) in cases.iter().enumerate() {
            if i == 0 {
                w.line(format!("\t{p}Tag{} = iota", go_pascal(c)));
            } else {
                w.line(format!("\t{p}Tag{}", go_pascal(c)));
            }
        }
        w.line(")");
        w.line("");
        for (c, payload) in cases {
            let cp = go_pascal(c);
            w.line(format!("// New{p}{cp} returns the `{c}` case of {p}."));
            match payload {
                None => {
                    w.open(format!("func New{p}{cp}() {p} {{"));
                    w.line(format!("return {p}{{Tag: {p}Tag{cp}}}"));
                    w.close("}");
                }
                Some(pt) => {
                    w.open(format!(
                        "func New{p}{cp}(payload {}) {p} {{",
                        go_ty(pt, "", 0)?
                    ));
                    w.line(format!("return {p}{{Tag: {p}Tag{cp}, {cp}: &payload}}"));
                    w.close("}");
                }
            }
            w.line("");
        }

        // encode
        let mut cx = Cx::new("return nil, err");
        let mut bw = W::new();
        bw.ind = 1;
        bw.open("switch v.Tag {");
        for (i, (c, payload)) in cases.iter().enumerate() {
            let cp = go_pascal(c);
            bw.ind -= 1;
            bw.line(format!("case {p}Tag{cp}:"));
            bw.ind += 1;
            match payload {
                None => bw.line(format!("out = EncodeCase(out, {i})")),
                Some(pt) => {
                    bw.open(format!("if v.{cp} == nil {{"));
                    bw.line(format!(
                        "return nil, errors.New(\"{p}: case {c} has a nil payload\")"
                    ));
                    bw.close("}");
                    bw.line(format!("out = EncodeCase(out, {i})"));
                    emit_encode_deref(&mut bw, &mut cx, pt, &format!("v.{cp}"))?;
                }
            }
        }
        bw.ind -= 1;
        bw.line("default:");
        bw.ind += 1;
        bw.line(format!(
            "return nil, fmt.Errorf(\"invalid {p} tag: %d\", v.Tag)"
        ));
        bw.close("}");
        let mut body = bw.buf;
        if cx.used_err {
            body = format!("\tvar err error\n{body}");
        }
        self.write_encode_helper(w, &p, body);

        // decode
        let mut cx = Cx::new("return");
        let mut bw = W::new();
        bw.ind = 1;
        bw.line("var c uint32");
        bw.line(format!("c, err = d.VariantCase({})", cases.len()));
        bw.open("if err != nil {");
        bw.line("return");
        bw.close("}");
        bw.line("v.Tag = int(c)");
        if cases.iter().any(|(_, p)| p.is_some()) {
            bw.open("switch c {");
            for (i, (c, payload)) in cases.iter().enumerate() {
                let Some(pt) = payload else { continue };
                bw.ind -= 1;
                bw.line(format!("case {i}:"));
                bw.ind += 1;
                let x = cx.fresh("x");
                bw.line(format!("var {x} {}", go_ty(pt, "", bw.ind)?));
                emit_decode(&mut bw, &mut cx, pt, &x)?;
                bw.line(format!("v.{} = &{x}", go_pascal(c)));
            }
            bw.close("}");
        }
        self.write_decode_helper(w, &p, &bw.buf);
        Ok(())
    }

    // -- function signatures ---------------------------------------------------

    /// "EchoEverything(e Everything) (Everything, error)" — shared by the
    /// Impl interface, the scaffolded stubs, and missing_impls output.
    fn method_sig(&self, f: &Func, qual: &str) -> Result<String> {
        let params = f
            .params
            .iter()
            .map(|(n, t)| Ok(format!("{} {}", go_param(n), go_ty(t, qual, 0)?)))
            .collect::<Result<Vec<_>>>()?
            .join(", ");
        let ret = match self.classify(f)?.value_ty() {
            Some(t) => format!("({}, error)", go_ty(t, qual, 0)?),
            None => "error".to_string(),
        };
        Ok(format!("{}({params}) {ret}", go_pascal(&f.wit_name)))
    }

    /// One doc line describing where a method's returned error goes.
    fn err_doc(&self, f: &Func) -> Result<&'static str> {
        Ok(match self.classify(f)? {
            Ret::ResStr { has_msg: true, .. } => {
                "// A non-nil error encodes as the WIT result err case (a normal status-0 reply)."
            }
            Ret::ResStr { has_msg: false, .. } => {
                "// A non-nil error encodes as the WIT result err case (no payload: the message is dropped)."
            }
            _ => "// A non-nil error is a function-level failure (status-1 reply).",
        })
    }

    // -- bindings.go -----------------------------------------------------------

    fn bindings_go(&self) -> Result<String> {
        let mut w = W::new();

        if self.need_result {
            w.line("// Result mirrors a WIT result<T, E> in value position: IsErr selects the");
            w.line("// populated side; sides with no payload use struct{}.");
            w.line("type Result[T any, E any] struct {");
            w.line("\tIsErr bool");
            w.line("\tOk    T");
            w.line("\tErr   E");
            w.line("}");
            w.line("");
        }

        for iface in self.m.exports.iter().chain(&self.m.imports) {
            for t in &iface.types {
                self.emit_named_ty(&mut w, iface, t)?;
            }
        }

        let export = &self.m.exports[0];
        w.line("// Impl is the application interface: one method per function exported by");
        w.line(format!(
            "// {}. impl.go implements it and registers the implementation",
            export.instance
        ));
        w.line("// via SetImpl from init().");
        w.open("type Impl interface {");
        for (i, f) in export.funcs.iter().enumerate() {
            if i > 0 {
                w.line("");
            }
            w.line(format!(
                "// {} handles {}#{}.",
                go_pascal(&f.wit_name),
                export.instance,
                f.wit_name
            ));
            w.line(self.err_doc(f)?);
            w.line(self.method_sig(f, "")?);
        }
        w.close("}");
        w.line("");
        w.line("var impl Impl");
        w.line("");
        w.line("// SetImpl registers the application implementation; the scaffolded impl.go");
        w.line("// calls it from init().");
        w.line("func SetImpl(i Impl) { impl = i }");
        w.line("");
        w.line("var errNoImpl = errors.New(\"no implementation registered: impl.go must call gen.SetImpl in init()\")");
        w.line("");

        for f in &export.funcs {
            self.emit_args_decoder(&mut w, f)?;
            self.emit_handler(&mut w, export, f)?;
        }

        if !export.funcs.is_empty() {
            w.open("func init() {");
            for f in &export.funcs {
                w.line(format!(
                    "handlers[\"{}#{}\"] = handle{}",
                    export.instance,
                    f.wit_name,
                    go_pascal(&f.wit_name)
                ));
            }
            w.close("}");
            w.line("");
        }

        let mut out = String::new();
        out.push_str(GENERATED_HEADER);
        out.push_str("\n//\n");
        out.push_str(&format!(
            "// Typed bindings for WIT package {}, world {}: native declarations for\n",
            self.m.package, self.m.world
        ));
        out.push_str("// every WIT type, straight-line WIRE codecs, the Impl interface the\n");
        out.push_str("// application implements (see impl.go), and the crab_invoke dispatch\n");
        out.push_str("// entries.\n");
        out.push_str("//\n");
        out.push_str("// Error semantics (WIRE.md): a method for a WIT function returning\n");
        out.push_str("// result<T, string> (or result with no err payload) maps a non-nil error\n");
        out.push_str("// to the WIRE result ERR CASE — a normal status-0 reply carrying an\n");
        out.push_str("// encoded result value. Every other method's non-nil error is a\n");
        out.push_str("// function-level failure: the runtime replies status 1 with\n");
        out.push_str("// \"<function>: <message>\".\n");
        out.push_str("package gen\n");
        // NB: imports_block is a substring scan that sees comments too: a
        // generated doc comment containing "fmt." or "errors." needlessly
        // forces the import (harmless) — it can over-include, never miss.
        out.push_str(&imports_block(&w.buf));
        out.push_str(&w.buf);
        Ok(trim_final(&out))
    }

    /// decode<Fn>Args: named results (typed params + err), straight-line
    /// Decoder calls, ALWAYS finishing with d.Finish("params").
    fn emit_args_decoder(&self, w: &mut W, f: &Func) -> Result<()> {
        let p = go_pascal(&f.wit_name);
        let mut sig_params = Vec::new();
        for (n, t) in &f.params {
            sig_params.push(format!("{} {}", go_param(n), go_ty(t, "", 0)?));
        }
        sig_params.push("err error".to_string());
        w.line(format!(
            "// decode{p}Args decodes the WIRE-encoded params of `{}`.",
            f.wit_name
        ));
        w.open(format!(
            "func decode{p}Args(d *Decoder) ({}) {{",
            sig_params.join(", ")
        ));
        let mut cx = Cx::new("return");
        for (n, t) in &f.params {
            let dest = go_param(n);
            emit_decode(w, &mut cx, t, &dest)?;
        }
        w.line("err = d.Finish(\"params\")");
        w.line("return");
        w.close("}");
        w.line("");
        Ok(())
    }

    fn emit_handler(&self, w: &mut W, iface: &Iface, f: &Func) -> Result<()> {
        let p = go_pascal(&f.wit_name);
        let params: Vec<String> = f.params.iter().map(|(n, _)| go_param(n)).collect();
        w.line(format!(
            "// handle{p} dispatches {}#{}; registered in init().",
            iface.instance, f.wit_name
        ));
        w.open(format!("func handle{p}(d *Decoder) ([]byte, error) {{"));
        w.open("if impl == nil {");
        w.line("return nil, errNoImpl");
        w.close("}");
        let mut lhs = params.clone();
        lhs.push("err".to_string());
        w.line(format!("{} := decode{p}Args(d)", lhs.join(", ")));
        w.open("if err != nil {");
        w.line("return nil, fmt.Errorf(\"bad params: %w\", err)");
        w.close("}");
        let call = format!("impl.{p}({})", params.join(", "));
        match self.classify(f)? {
            Ret::None => {
                w.open(format!("if err := {call}; err != nil {{"));
                w.line("return nil, err");
                w.close("}");
                w.line("return nil, nil");
            }
            Ret::Plain(t) => {
                w.line(format!("r, err := {call}"));
                w.open("if err != nil {");
                w.line("return nil, err");
                w.close("}");
                w.line("var out []byte");
                let mut cx = Cx::new("return nil, err");
                emit_encode(w, &mut cx, t, "r")?;
                w.line("return out, nil");
            }
            Ret::ResStr { ok, has_msg } => {
                match ok {
                    Some(_) => w.line(format!("r, err := {call}")),
                    None => w.line(format!("err = {call}")),
                }
                w.line("var out []byte");
                w.open("if err != nil {");
                w.line("out = EncodeResultTag(out, true)");
                if has_msg {
                    w.line("out = EncodeString(out, err.Error())");
                } else {
                    w.line("// the WIT err side has no payload: the message is dropped");
                }
                w.line("return out, nil");
                w.close("}");
                w.line("out = EncodeResultTag(out, false)");
                if let Some(okt) = ok {
                    let mut cx = Cx::new("return nil, err");
                    emit_encode(w, &mut cx, okt, "r")?;
                }
                w.line("return out, nil");
            }
            Ret::ResTyped(t) => {
                w.line(format!("r, err := {call}"));
                w.open("if err != nil {");
                w.line("return nil, err");
                w.close("}");
                w.line("var out []byte");
                let mut cx = Cx::new("return nil, err");
                emit_encode(w, &mut cx, t, "r")?;
                w.line("return out, nil");
            }
        }
        w.close("}");
        w.line("");
        Ok(())
    }

    // -- imports.go (mesh wrappers) ---------------------------------------------

    fn imports_go(&self) -> Result<String> {
        let mut w = W::new();
        for iface in &self.m.imports {
            let ip = go_pascal(iface_short(&iface.instance));
            for f in &iface.funcs {
                self.emit_mesh_wrapper(&mut w, iface, &ip, f)?;
            }
        }
        let mut out = String::new();
        out.push_str(GENERATED_HEADER);
        out.push_str("\n//\n");
        out.push_str("// Typed mesh wrappers for the world's imported interfaces: each function\n");
        out.push_str(
            "// becomes a package-level wrapper that WIRE-encodes its params, calls the\n",
        );
        out.push_str("// named workload through the host mesh (crabcraft.call import), and\n");
        out.push_str("// decodes the reply. The caller names the target deployment — crabgen\n");
        out.push_str("// never bakes one in; placement is the host's problem.\n");
        out.push_str("package gen\n");
        // NB: imports_block is a substring scan that sees comments too: a
        // generated doc comment containing "fmt." or "errors." needlessly
        // forces the import (harmless) — it can over-include, never miss.
        out.push_str(&imports_block(&w.buf));
        out.push_str(&w.buf);
        Ok(trim_final(&out))
    }

    fn emit_mesh_wrapper(&self, w: &mut W, iface: &Iface, ip: &str, f: &Func) -> Result<()> {
        let name = format!("{ip}{}", go_pascal(&f.wit_name));
        let addr = format!("{}#{}", iface.instance, f.wit_name);
        let ret = self.classify(f)?;
        let mut sig_params = vec!["workload string".to_string()];
        for (n, t) in &f.params {
            sig_params.push(format!("{} {}", go_param(n), go_ty(t, "", 0)?));
        }
        let sig_ret = match ret.value_ty() {
            Some(t) => format!("(r {}, err error)", go_ty(t, "", 0)?),
            None => "(err error)".to_string(),
        };
        w.line(format!("// {name} calls {addr} on the workload named"));
        w.line("// `workload` through the host mesh. The returned error covers transport");
        let res_note = match ret {
            Ret::ResStr { .. } => {
                "// failures, remote status-1 failures, AND the WIT result err case."
            }
            _ => "// failures and remote status-1 failures.",
        };
        w.line(res_note);
        w.open(format!(
            "func {name}({}) {sig_ret} {{",
            sig_params.join(", ")
        ));
        // encode params
        let call_params = if f.params.is_empty() {
            "nil".to_string()
        } else {
            w.line("var out []byte");
            let mut cx = Cx::new("return");
            for (n, t) in &f.params {
                emit_encode(w, &mut cx, t, &go_param(n))?;
            }
            "out".to_string()
        };
        w.line("var body []byte");
        w.line(format!(
            "body, err = MeshCall(workload, \"{addr}\", {call_params})"
        ));
        w.open("if err != nil {");
        w.line("return");
        w.close("}");
        w.line("d := NewDecoder(body)");
        match ret {
            Ret::None => {
                w.line("err = d.Finish(\"reply\")");
                w.line("return");
            }
            Ret::Plain(t) => {
                let mut cx = Cx::new("return");
                emit_decode(w, &mut cx, t, "r")?;
                w.line("err = d.Finish(\"reply\")");
                w.line("return");
            }
            Ret::ResTyped(t) => {
                let mut cx = Cx::new("return");
                emit_decode(w, &mut cx, t, "r")?;
                w.line("err = d.Finish(\"reply\")");
                w.line("return");
            }
            Ret::ResStr { ok, has_msg } => {
                let mut cx = Cx::new("return");
                w.line("var isErr bool");
                w.line("isErr, err = d.ResultTag()");
                w.open("if err != nil {");
                w.line("return");
                w.close("}");
                w.open("if isErr {");
                if has_msg {
                    w.line("var msg string");
                    w.line("msg, err = d.String()");
                    w.open("if err != nil {");
                    w.line("return");
                    w.close("}");
                    w.open("if err = d.Finish(\"reply\"); err != nil {");
                    w.line("return");
                    w.close("}");
                    w.line("err = errors.New(msg)");
                } else {
                    w.open("if err = d.Finish(\"reply\"); err != nil {");
                    w.line("return");
                    w.close("}");
                    w.line(format!(
                        "err = errors.New(\"{}: err result (no payload)\")",
                        f.wit_name
                    ));
                }
                w.line("return");
                w.close("}");
                if let Some(okt) = ok {
                    emit_decode(w, &mut cx, okt, "r")?;
                }
                w.line("err = d.Finish(\"reply\")");
                w.line("return");
            }
        }
        w.close("}");
        w.line("");
        Ok(())
    }

    // -- scaffold files ----------------------------------------------------------

    fn impl_go(&self) -> Result<String> {
        let export = &self.m.exports[0];
        let mut w = W::new();
        w.line("// impl.go — the application half of this guest: implement gen.Impl here.");
        w.line("// crabgen scaffolds this file ONCE and never overwrites it; `crabgen regen`");
        w.line("// prints any missing method signatures instead of editing it.");
        w.line("package main");
        w.line("");
        if export.funcs.is_empty() {
            w.line(format!("import \"crabcraft.local/{}/gen\"", self.project));
        } else {
            w.line("import (");
            w.line("\t\"fmt\"");
            w.line("");
            w.line(format!("\t\"crabcraft.local/{}/gen\"", self.project));
            w.line(")");
        }
        w.line("");
        w.line("// App implements gen.Impl: one method per function exported by");
        w.line(format!("// {}.", export.instance));
        w.line("type App struct{}");
        w.line("");
        for f in &export.funcs {
            w.line(format!(
                "// {} handles {}#{}.",
                go_pascal(&f.wit_name),
                export.instance,
                f.wit_name
            ));
            w.line(self.err_doc(f)?);
            w.open(format!("func (App) {} {{", self.method_sig(f, "gen.")?));
            let unimpl = format!("fmt.Errorf(\"unimplemented: {}\")", f.wit_name);
            match self.classify(f)?.value_ty() {
                Some(t) => w.line(format!("return {}, {unimpl}", self.zero(t, "gen.", 1)?)),
                None => w.line(format!("return {unimpl}")),
            }
            w.close("}");
            w.line("");
        }
        w.line("func init() { gen.SetImpl(App{}) }");
        w.line("");
        w.line("// main never runs: the module builds as a wasip1 reactor (the host calls");
        w.line("// _initialize once, then crab_invoke per request).");
        w.line("func main() {}");
        Ok(trim_final(&w.buf))
    }
}

/// "crab:full/telemetry@0.1.0" → "telemetry"
fn iface_short(instance: &str) -> &str {
    let after = instance.rsplit('/').next().unwrap_or(instance);
    after.split('@').next().unwrap_or(after)
}

/// Build the import block for a generated gen file by scanning the body for
/// stdlib usage (the only candidates are errors and fmt).
fn imports_block(body: &str) -> String {
    let errors = body.contains("errors.");
    let fmt = body.contains("fmt.");
    match (errors, fmt) {
        (true, true) => "\nimport (\n\t\"errors\"\n\t\"fmt\"\n)\n\n".to_string(),
        (true, false) => "\nimport \"errors\"\n\n".to_string(),
        (false, true) => "\nimport \"fmt\"\n\n".to_string(),
        (false, false) => "\n".to_string(),
    }
}

/// Exactly one trailing newline (gofmt).
fn trim_final(s: &str) -> String {
    format!("{}\n", s.trim_end())
}

