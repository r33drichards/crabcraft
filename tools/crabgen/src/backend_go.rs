impl Backend for GoBackend {
    fn lang(&self) -> &'static str {
        "go"
    }

    fn impl_ext(&self) -> &'static str {
        "go"
    }

    fn generate(&self, m: &Module, dir: &Path) -> Result<()> {
        let g = Gen::new(m, &project_name(dir)?)?;
        let gen_dir = dir.join("gen");
        let write = |name: &str, content: &str| -> Result<()> {
            let path = gen_dir.join(name);
            fs::write(&path, content).with_context(|| format!("writing {}", path.display()))
        };
        write("runtime.go", RUNTIME_GO)?;
        write("runtime_test.go", RUNTIME_TEST_GO)?;
        write("schema.go", &schema_go())?;
        write("bindings.go", &g.bindings_go()?)?;
        if !m.imports.is_empty() {
            write("mesh.go", MESH_GO)?;
            write("mesh_wasm.go", MESH_WASM_GO)?;
            write("mesh_test.go", MESH_TEST_GO)?;
            write("imports.go", &g.imports_go()?)?;
        }
        // README quotes WIT-derived content (the export instance), so it is
        // regenerated alongside gen/ — the canonical flow swaps the starter
        // WIT and regens, which must not leave stale docs. It lives at the
        // project root, not gen/.
        let readme_path = dir.join("README.md");
        fs::write(&readme_path, readme(&project_name(dir)?, m))
            .with_context(|| format!("writing {}", readme_path.display()))?;
        Ok(())
    }

    fn scaffold(&self, m: &Module, dir: &Path) -> Result<()> {
        let name = project_name(dir)?;
        let g = Gen::new(m, &name)?;
        let write_once = |path: &Path, content: &str| -> Result<()> {
            if !path.exists() {
                fs::write(path, content).with_context(|| format!("writing {}", path.display()))?;
            }
            Ok(())
        };
        write_once(&dir.join("impl.go"), &g.impl_go()?)?;
        write_once(&dir.join("go.mod"), &go_mod(&name))?;
        let build = dir.join("build.sh");
        if !build.exists() {
            fs::write(&build, build_sh(&name))?;
            let mut perms = fs::metadata(&build)?.permissions();
            perms.set_mode(0o755);
            fs::set_permissions(&build, perms)?;
        }
        Ok(())
    }

    fn missing_impls(&self, m: &Module, dir: &Path) -> Result<Vec<String>> {
        let g = Gen::new(m, &project_name(dir)?)?;
        let src = fs::read_to_string(dir.join("impl.go")).unwrap_or_default();
        let mut missing = Vec::new();
        for iface in &m.exports {
            for f in &iface.funcs {
                let go_name = go_pascal(&f.wit_name);
                if !src.contains(&format!(") {go_name}(")) {
                    missing.push(format!("func (App) {}", g.method_sig(f, "gen.")?));
                }
            }
        }
        Ok(missing)
    }
}

fn project_name(dir: &Path) -> Result<String> {
    dir.file_name()
        .map(|n| n.to_string_lossy().to_string())
        .ok_or_else(|| anyhow!("project dir {} has no name", dir.display()))
}

