/// kebab-case → PascalCase: Title each dash segment ("a-u8" → "AU8").
fn go_pascal(kebab: &str) -> String {
    kebab
        .split('-')
        .map(|seg| {
            let mut c = seg.chars();
            match c.next() {
                Some(f) => f.to_ascii_uppercase().to_string() + c.as_str(),
                None => String::new(),
            }
        })
        .collect()
}

/// kebab-case → lowerCamel parameter name, underscore-mangled away from Go
/// keywords/predeclared names/generated locals and temp-name patterns.
fn go_param(kebab: &str) -> String {
    let mut segs = kebab.split('-');
    let mut s = segs.next().unwrap_or_default().to_string();
    for seg in segs {
        s.push_str(&go_pascal(seg));
    }
    if PARAM_AVOID.contains(&s.as_str()) || is_temp_shaped(&s) {
        s.push('_');
    }
    s
}

/// Matches the generated temp-name pattern (x0, n1, i2, ok0, isErr0...).
fn is_temp_shaped(s: &str) -> bool {
    for prefix in ["x", "n", "i", "ok", "isErr"] {
        if let Some(rest) = s.strip_prefix(prefix) {
            if !rest.is_empty() && rest.bytes().all(|b| b.is_ascii_digit()) {
                return true;
            }
        }
    }
    false
}

