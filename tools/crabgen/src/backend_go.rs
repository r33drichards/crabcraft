/// Line writer with tab indentation (gofmt's). `line` may carry embedded
/// newlines (multiline anonymous struct types render their own inner tabs).
struct W {
    buf: String,
    ind: usize,
}

impl W {
    fn new() -> Self {
        W {
            buf: String::new(),
            ind: 0,
        }
    }

    fn line(&mut self, s: impl AsRef<str>) {
        let s = s.as_ref();
        if !s.is_empty() {
            for _ in 0..self.ind {
                self.buf.push('\t');
            }
            self.buf.push_str(s);
        }
        self.buf.push('\n');
    }

    fn open(&mut self, s: impl AsRef<str>) {
        self.line(s);
        self.ind += 1;
    }

    fn close(&mut self, s: impl AsRef<str>) {
        self.ind -= 1;
        self.line(s);
    }
}

/// Per-function emission state: fresh temp names, the error-return statement
/// for the current context, and whether an `err` assignment was emitted (so
/// encode helpers know to declare `var err error`).
struct Cx {
    tmp: usize,
    ret: &'static str,
    used_err: bool,
}

impl Cx {
    fn new(ret: &'static str) -> Self {
        Cx {
            tmp: 0,
            ret,
            used_err: false,
        }
    }

    fn fresh(&mut self, base: &str) -> String {
        let n = self.tmp;
        self.tmp += 1;
        format!("{base}{n}")
    }
}

/// gofmt's struct-field alignment: within a section, names are space-padded
/// to the longest name + 1; a field whose type spans multiple lines is the
/// LAST member of its section (verified against gofmt empirically).
fn align_fields(fields: &[(String, String)], ind: usize) -> String {
    let tab = "\t".repeat(ind);
    let mut out = String::new();
    let mut i = 0;
    while i < fields.len() {
        let mut j = i;
        while j < fields.len() && !fields[j].1.contains('\n') {
            j += 1;
        }
        let end = (j + 1).min(fields.len());
        let maxn = fields[i..end].iter().map(|(n, _)| n.len()).max().unwrap();
        for (name, ty) in &fields[i..end] {
            let pad = " ".repeat(maxn - name.len());
            out.push_str(&format!("{tab}{name}{pad} {ty}\n"));
        }
        i = end;
    }
    out
}

/// Scalar types: (Encode* function, Decoder method, Go type).
fn scalar(ty: &Ty) -> Option<(&'static str, &'static str, &'static str)> {
    Some(match ty {
        Ty::Bool => ("EncodeBool", "Bool", "bool"),
        Ty::U8 => ("EncodeU8", "U8", "uint8"),
        Ty::U16 => ("EncodeU16", "U16", "uint16"),
        Ty::U32 => ("EncodeU32", "U32", "uint32"),
        Ty::U64 => ("EncodeU64", "U64", "uint64"),
        Ty::S8 => ("EncodeS8", "S8", "int8"),
        Ty::S16 => ("EncodeS16", "S16", "int16"),
        Ty::S32 => ("EncodeS32", "S32", "int32"),
        Ty::S64 => ("EncodeS64", "S64", "int64"),
        Ty::F32 => ("EncodeF32", "F32", "float32"),
        Ty::F64 => ("EncodeF64", "F64", "float64"),
        Ty::Char => ("EncodeChar", "Char", "rune"),
        Ty::String => ("EncodeString", "String", "string"),
        _ => return None,
    })
}

/// A type that encodes to zero bytes (empty tuple): encode emits no
/// statements for it, so deref temps must not be created.
fn is_unit(ty: &Ty) -> bool {
    matches!(ty, Ty::Tuple(ts) if ts.is_empty())
}

/// Go type expression for a value-position type. `qual` is "" inside
/// package gen, "gen." in impl.go signatures. `ind` is the indent level
/// of the line the type starts on (anonymous tuple structs span lines).
fn go_ty(ty: &Ty, qual: &str, ind: usize) -> Result<String> {
    Ok(match ty {
        Ty::List(t) => format!("[]{}", go_ty(t, qual, ind)?),
        Ty::Option(t) => format!("*{}", go_ty(t, qual, ind)?),
        Ty::Tuple(ts) => {
            if ts.is_empty() {
                "struct{}".to_string()
            } else {
                let fields = ts
                    .iter()
                    .enumerate()
                    .map(|(i, t)| Ok((format!("F{i}"), go_ty(t, qual, ind + 1)?)))
                    .collect::<Result<Vec<_>>>()?;
                format!(
                    "struct {{\n{}{}}}",
                    align_fields(&fields, ind + 1),
                    "\t".repeat(ind)
                )
            }
        }
        Ty::Result(ok, errt) => {
            let side = |t: &Option<Box<Ty>>| -> Result<String> {
                Ok(match t {
                    Some(t) => go_ty(t, qual, ind)?,
                    None => "struct{}".to_string(),
                })
            };
            format!("{qual}Result[{}, {}]", side(ok)?, side(errt)?)
        }
        Ty::Named(n) => format!("{qual}{}", go_pascal(n)),
        Ty::Record(_) | Ty::Variant(_) | Ty::Enum(_) | Ty::Flags(_) => {
            bail!("internal error: anonymous {ty:?} cannot appear in value position (WIT names these)")
        }
        _ => scalar(ty)
            .map(|(_, _, go)| go.to_string())
            .ok_or_else(|| anyhow!("unmapped type {ty:?}"))?,
    })
}

/// How a function's WIT result maps onto its Go signature.
enum Ret<'a> {
    /// no WIT result → `error` (non-nil = status-1 reply)
    None,
    /// plain value → `(T, error)` (non-nil = status-1 reply)
    Plain(&'a Ty),
    /// result<T, string> / result<T> / result<_,_> → `(T, error)` / `error`;
    /// a non-nil error is the WIRE result ERR CASE (status stays 0).
    /// `has_msg` = the err side carries the string payload.
    ResStr { ok: Option<&'a Ty>, has_msg: bool },
    /// result with any other err type → `(Result[T, E], error)`
    /// (non-nil error = status-1 reply)
    ResTyped(&'a Ty),
}

impl<'a> Ret<'a> {
    /// The Go value type returned ahead of `error`, if any.
    fn value_ty(&self) -> Option<&'a Ty> {
        match self {
            Ret::None => None,
            Ret::Plain(t) => Some(t),
            Ret::ResStr { ok, .. } => *ok,
            Ret::ResTyped(t) => Some(t),
        }
    }
}

