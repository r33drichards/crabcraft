//! Go backend: typed bindings + dispatch + mesh wrappers + scaffold over the
//! templates/go runtime (TinyGo wasip1 reactor lane).
//!
//! Type mapping (WIT → Go):
//!
//! | WIT              | Go                                                       |
//! |------------------|----------------------------------------------------------|
//! | bool             | bool                                                     |
//! | u8 u16 u32 u64   | uint8 uint16 uint32 uint64                               |
//! | s8 s16 s32 s64   | int8 int16 int32 int64                                   |
//! | f32 f64          | float32 float64                                          |
//! | char             | rune (validated unicode scalar on the wire)              |
//! | string           | string                                                   |
//! | list<T>          | []T (decode pre-allocation clamped at 4096)              |
//! | option<T>        | *T (nil = none)                                          |
//! | tuple<A, B, ..>  | anonymous struct{ F0 A; F1 B; .. }                       |
//! | record           | struct with exported Go-cased fields                     |
//! | variant          | struct{ Tag int; <Case> *T per payload case } + tag      |
//! |                  | consts + New<Variant><Case> constructors                 |
//! | enum             | type X int + consts in declaration order                 |
//! | flags            | type X uint64 + 1<<i bit consts (max 64 flags)           |
//! | result<T, E>     | value position: generic Result[T, E] (struct{} stands in |
//! |                  | for absent sides). Function-RESULT position with E =     |
//! |                  | string or absent: idiomatic Go (T, error) / error — a    |
//! |                  | non-nil error encodes as the WIRE result err case        |
//! |                  | (status stays 0); for any other E the method returns     |
//! |                  | (Result[T, E], error) and the error means status 1.      |
//!
//! Name casing: WIT kebab-case → Go by Title-casing each dash segment
//! ("echo-everything" → "EchoEverything", "a-u8" → "AU8" — no smart acronym
//! table, the per-segment Title is the whole rule). Parameters are
//! lowerCamel ("a-bool" → "aBool"); parameter names that would collide with
//! Go keywords, predeclared identifiers, or locals the generated code uses
//! get a trailing underscore.
//!
//! Declaration order: types are emitted in WIT declaration order, exports
//! before imports. Go top-level declarations are order-independent, so no
//! dependency sorting is needed (recursive references via Named just work).
//!
//! Error semantics (WIRE.md section 2): the runtime's crab_invoke maps a
//! handler error to a status-1 reply "<function>: <message>". Generated
//! handlers add "bad params: " context to decode failures and always check
//! d.Finish("params"); impl errors pass through (or become the result err
//! case, see the table above).
//!
//! Collisions: every emitted top-level identifier is checked against the
//! runtime/template identifiers and each other; a WIT name that maps onto a
//! taken Go identifier (e.g. a type named `impl` → `Impl`) fails generate()
//! with both names in the message instead of emitting broken code.

